<script>
    let activeStage = 'all';
    let activeFormat = 'all';

    function setSearchValue(query) {
      const input = document.getElementById('resourceSearchInput');
      if (input) {
        input.value = query;
        input.focus();
        applyFilters();
      }
    }

    function filterByStage(stage, tabElement) {
      activeStage = stage;
      
      // Update Tab Styles
      const allTabs = document.querySelectorAll('.stage-tab');
      allTabs.forEach(tab => {
        tab.classList.remove('ring-2', 'ring-primary', 'active-stage');
      });
      if (tabElement) {
        tabElement.classList.add('ring-2', 'ring-primary', 'active-stage');
      }

      applyFilters();
    }

    function setFormatFilter(format, pillElement) {
      activeFormat = format;

      // Update Pill styles
      const allPills = document.querySelectorAll('.format-pill');
      allPills.forEach(pill => {
        pill.classList.remove('bg-primary', 'text-on-primary', 'font-bold');
        pill.classList.add('bg-surface-container-lowest', 'text-on-surface-variant', 'font-medium');
      });

      if (pillElement) {
        pillElement.classList.remove('bg-surface-container-lowest', 'text-on-surface-variant', 'font-medium');
        pillElement.classList.add('bg-primary', 'text-on-primary', 'font-bold');
      }

      applyFilters();
    }

    function applyFilters() {
      const accessValue = document.getElementById('accessFilter') ? document.getElementById('accessFilter').value : 'all';
      const topicValue = document.getElementById('topicFilter') ? document.getElementById('topicFilter').value : 'all';
      const searchQuery = document.getElementById('resourceSearchInput') ? document.getElementById('resourceSearchInput').value.toLowerCase().trim() : '';

      const cards = document.querySelectorAll('.resource-card');
      let visibleCount = 0;

      cards.forEach(card => {
        const cardFormat = card.getAttribute('data-format');
        const cardStage = card.getAttribute('data-stage');
        const cardAccess = card.getAttribute('data-access');
        const cardTopic = card.getAttribute('data-topic');
        const textContent = card.innerText.toLowerCase();

        const matchFormat = (activeFormat === 'all' || cardFormat === activeFormat);
        const matchStage = (activeStage === 'all' || cardStage === activeStage);
        const matchAccess = (accessValue === 'all' || cardAccess === accessValue);
        const matchTopic = (topicValue === 'all' || cardTopic === topicValue);
        const matchSearch = (searchQuery === '' || textContent.includes(searchQuery));

        if (matchFormat && matchStage && matchAccess && matchTopic && matchSearch) {
          card.classList.remove('hidden');
          visibleCount++;
        } else {
          card.classList.add('hidden');
        }
      });

      // Update Count Badge
      const countBadge = document.getElementById('resourceCountBadge');
      if (countBadge) {
        countBadge.textContent = `${visibleCount} Resources`;
      }

      // Show/Hide Empty State
      const noResults = document.getElementById('noResultsState');
      if (noResults) {
        if (visibleCount === 0) {
          noResults.classList.remove('hidden');
        } else {
          noResults.classList.add('hidden');
        }
      }
    }

    function resetFilters() {
      activeStage = 'all';
      activeFormat = 'all';

      const searchInput = document.getElementById('resourceSearchInput');
      if (searchInput) searchInput.value = '';

      const accessFilter = document.getElementById('accessFilter');
      if (accessFilter) accessFilter.value = 'all';

      const topicFilter = document.getElementById('topicFilter');
      if (topicFilter) topicFilter.value = 'all';

      const firstTab = document.querySelector('.stage-tab');
      filterByStage('all', firstTab);

      const firstPill = document.querySelector('.format-pill');
      setFormatFilter('all', firstPill);
    }

    // Attach search input listener
    document.addEventListener('DOMContentLoaded', () => {
      const searchInput = document.getElementById('resourceSearchInput');
      if (searchInput) {
        searchInput.addEventListener('input', applyFilters);
      }
    });
  </script>
